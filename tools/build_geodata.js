// Generates prototype/geodata.js from published open datasets.
//
//   npm install world-atlas@2.0.2 topojson-client@3.1.0 cities.json@1.1.66   (in a scratch folder)
//   node tools/build_geodata.js <path-to-that-folder/node_modules>
//
// Sources
// - DRC national outline: Natural Earth 1:50m admin-0 (public domain), via world-atlas (ISC).
// - Points: GeoNames populated places (CC BY 4.0), via cities.json. Only exact-name matches
//   inside the DRC are used, and each was checked by hand for plausibility; ambiguous matches
//   are excluded rather than guessed (see EXCLUDED). No coordinate is invented.
// Province and health-zone boundaries are NOT included: no open, versioned DRC admin-1/health-zone
// boundary set was available to this build. They must come from the MoH/DSNIS (or GRID3) files.
const path = require('path');
const fs = require('fs');
const nm = process.argv[2];
if (!nm) { console.error('usage: node tools/build_geodata.js <node_modules dir>'); process.exit(1); }
const req = (m) => require(path.join(nm, m));
const topo = req('topojson-client');
const world = req('world-atlas/countries-50m.json');
const cities = req('cities.json').filter((c) => c.country === 'CD');

const drc = topo.feature(world, world.objects.countries).features.find((f) => f.id === '180');
const round = (x) => Math.round(x * 1000) / 1000;
const outline = drc.geometry.coordinates.map((ring) => ring.map(([x, y]) => [round(x), round(y)]));

// Provincial capitals (administrative fact; coordinates from GeoNames).
const CAPITALS = {
  'Bas-Uele': 'Buta', 'Equateur': 'Mbandaka', 'Haut-Katanga': 'Lubumbashi', 'Haut-Lomami': 'Kamina',
  'Haut-Uele': 'Isiro', 'Ituri': 'Bunia', 'Kasaï': 'Tshikapa', 'Kasaï-Central': 'Kananga',
  'Kasaï-Oriental': 'Mbuji-Mayi', 'Kinshasa': 'Kinshasa', 'Kongo-Central': 'Matadi', 'Kwango': 'Kenge',
  'Kwilu': 'Bandundu', 'Lomami': 'Kabinda', 'Lualaba': 'Kolwezi', 'Mai-Ndombe': 'Inongo', 'Maniema': 'Kindu',
  'Mongala': 'Lisala', 'Nord-Kivu': 'Goma', 'Nord-Ubangi': 'Gbadolite', 'Sankuru': 'Lusambo',
  'Sud-Kivu': 'Bukavu', 'Sud-Ubangi': 'Gemena', 'Tanganyika': 'Kalemie', 'Tshopo': 'Kisangani', 'Tshuapa': 'Boende'
};
// Matches rejected after review: the GeoNames "Kenge" found lies near Matadi (Kongo-Central), not the
// capital of Kwango; "Bandundu" has no unambiguous city entry in this dataset.
const EXCLUDED = { 'Kwango': 'ambiguous GeoNames match (Kenge near Matadi)', 'Kwilu': 'no unambiguous GeoNames match for Bandundu' };
// Supplied health-zone names that match a DRC populated place of the same name.
const ZONE_TOWNS = ['Aba', 'Abuzi', 'Adi', 'Adja', 'Aketi', 'Alimbongo', 'Alunguli', 'Ango', 'Angumu', 'Ankoro', 'Ariwara', 'Aru', 'Aungba',
  'Bafwagbogbo', 'Bafwasende', 'Bagata', 'Bagira', 'Baka', 'Bambo', 'Bambu', 'Banalia', 'Bandalungwa', 'Bandundu', 'Banga Lubaka', 'Bangabola', 'Banzow Moke'];

const norm = (s) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z]/g, '');
const find = (name) => cities.filter((c) => norm(c.name) === norm(name));

const provinces = {};
for (const [prov, cap] of Object.entries(CAPITALS)) {
  const m = find(cap);
  if (EXCLUDED[prov] || m.length !== 1) { provinces[prov] = { capital: cap, status: 'not_geocoded', note: EXCLUDED[prov] || 'no unique match' }; continue; }
  provinces[prov] = { capital: cap, lat: +(+m[0].lat).toFixed(4), lon: +(+m[0].lng).toFixed(4), status: 'approximate', source: 'GeoNames (provincial capital)' };
}
const zones = {};
for (const z of ZONE_TOWNS) {
  const m = find(z);
  if (m.length === 1) zones[z] = { lat: +(+m[0].lat).toFixed(4), lon: +(+m[0].lng).toFixed(4), status: 'approximate', source: 'GeoNames (town of the same name; not a health-zone centroid)' };
}

const out = {
  generated: new Date().toISOString().slice(0, 10),
  attribution: 'Outline: Natural Earth (public domain) via world-atlas. Points: GeoNames (CC BY 4.0) via cities.json.',
  boundaries_note: 'Province and health-zone boundaries not included: to be supplied by MoH/DSNIS (official shapefiles).',
  bbox: [12.0, -13.6, 31.4, 5.5],
  outline,
  provinces,
  zones
};
fs.writeFileSync(path.join(__dirname, '..', 'prototype', 'geodata.js'),
  '/* GENERATED by tools/build_geodata.js - do not edit. ' + out.attribution + ' */\nwindow.BDBV_GEODATA = ' + JSON.stringify(out) + ';\n');
console.log('geodata.js written:', Object.values(provinces).filter((p) => p.lat).length, 'provinces geocoded,', Object.keys(zones).length, 'zones geocoded,', outline[0].length, 'outline points');
